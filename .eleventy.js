const path = require("path");
const Image = require("@11ty/eleventy-img");
const registerGalleryShortcodes = require("./eleventy/gallery.js");
const registerCvShortcodes = require("./eleventy/cv.js");
const registerCvPdf = require("./eleventy/cv-pdf.js");
const site = require("./src/_data/site.js");

const OUTPUT_DIR = "./dist/img/";
const URL_PATH = "/img/";

// Source file names are not always URL-safe (accents, "©", spaces...). Only the
// names of the generated variants (the URLs in dist/) are sanitised, never the
// source file in src/.
function slugifyBasename(src) {
  const base = path.basename(src, path.extname(src));
  return base
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "") // strip accents (á -> a)
    .replace(/[^a-zA-Z0-9._-]+/g, "-") // "©", spaces, etc. -> "-"
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "");
}

// Single image with responsive AVIF / WebP / JPEG variants.
async function imageShortcode(src, alt, sizes = "(max-width: 768px) 100vw, 720px") {
  const metadata = await Image(src, {
    widths: [320, 640, 1024],
    formats: ["avif", "webp", "jpeg"],
    outputDir: OUTPUT_DIR,
    urlPath: URL_PATH,
    // `id` is a hash of the source image: when you replace a photo keeping its
    // file name, the output gets a new name instead of reusing the old one.
    filenameFormat: (id, file, width, format) => `${slugifyBasename(file)}-${id}-${width}.${format}`,
    sharpOptions: { fit: "inside" },
    formatOptions: {
      jpeg: { quality: 82, mozjpeg: true },
      webp: { quality: 80 },
      avif: { quality: 50 }
    }
  });

  return Image.generateHTML(metadata, {
    alt,
    sizes,
    loading: "lazy",
    decoding: "async"
  });
}

module.exports = function (eleventyConfig) {
  // Everything in src/css (stylesheets and self-hosted fonts) is copied as is.
  // With `npm start` the dev server picks up changes to it automatically.
  eleventyConfig.addPassthroughCopy({ "src/css": "css" });

  // Favicons and icons.
  eleventyConfig.addPassthroughCopy({ "src/images/icons": "images" });

  // Social icons used by the footer (see `social` in src/_data/site.js).
  eleventyConfig.addPassthroughCopy({ "src/images/social": "images/social" });

  // Apache cache and compression rules (ignored by other hosts).
  eleventyConfig.addPassthroughCopy({ "config/.htaccess": ".htaccess" });

  // Global data available in every template.
  eleventyConfig.addGlobalData("year", new Date().getFullYear());
  // The stylesheets and scripts have no content hash in their file names, so
  // they are requested as "?v=<build>" to allow long caching without serving a
  // stale version after the next deploy.
  eleventyConfig.addGlobalData("buildTime", Date.now());
  // NOINDEX=1 asks search engines to skip the whole site (for demos and
  // staging copies).
  eleventyConfig.addGlobalData("noindexSite", process.env.NOINDEX === "1");

  // {% image "src/images/photo.jpg", "Alt text" %}
  eleventyConfig.addNunjucksAsyncShortcode("image", imageShortcode);

  // {% youtube "VIDEO_ID" %} or {% youtube "VIDEO_ID", 40 %} (start second).
  // Uses the cookie-less youtube-nocookie.com domain.
  eleventyConfig.addShortcode("youtube", function (id, start) {
    const query = start ? `?start=${parseInt(start, 10)}` : "";
    return `
      <div class="video">
        <iframe
          src="https://www.youtube-nocookie.com/embed/${id}${query}"
          title="YouTube video"
          allowfullscreen
          loading="lazy">
        </iframe>
      </div>
    `;
  });

  // Galleries: {% gallery %} and {% selectedWorks %}
  registerGalleryShortcodes(eleventyConfig);

  // Curriculum page (/cv/): the {% cvsection %} shortcode.
  registerCvShortcodes(eleventyConfig);

  // PDF of the curriculum (/curriculum.pdf), generated by printing /cv/ with a
  // headless Chrome, Edge or Chromium. On by default; set `cvPdf: false` in
  // src/_data/site.js to turn it off. It never breaks the build: with no
  // browser available it prints a warning and skips the PDF (and the "Download
  // PDF" link). See docs/cv.md.
  if (site.cvPdf) {
    registerCvPdf(eleventyConfig);
  }
  eleventyConfig.addGlobalData("cvPdfLink", Boolean(site.cvPdf) && registerCvPdf.canGenerate());

  return {
    dir: {
      input: "src",
      includes: "_includes",
      layouts: "_includes/layouts",
      output: "dist"
    },
    markdownTemplateEngine: "njk",
    htmlTemplateEngine: "njk",
    dataTemplateEngine: "njk"
  };
};
